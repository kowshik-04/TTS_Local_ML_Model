"""Discovery of generated audio and JSON metadata sidecars."""

from __future__ import annotations

import json
import os
import re
import tempfile
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import soundfile as sf


APP_OWNER = "telugu-voice-lab"
_STEM = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
_AUDIO_SUFFIXES = (".wav", ".mp3")


@dataclass(frozen=True)
class HistoryItem:
    stem: str
    wav_path: Path | None
    mp3_path: Path | None
    metadata: dict | None
    malformed_metadata: bool
    modified: float
    size_bytes: int
    duration_seconds: float | None

    @property
    def legacy(self) -> bool:
        return self.metadata is None

    @property
    def primary(self) -> Path:
        return self.wav_path or self.mp3_path

    @property
    def text(self) -> str:
        return str((self.metadata or {}).get("text", ""))

    @property
    def owned_by_app(self) -> bool:
        return bool(self.metadata) and self.metadata.get("owner") == APP_OWNER

    @property
    def created(self) -> str:
        created = (self.metadata or {}).get("created_at")
        if isinstance(created, str) and created:
            return created.replace("T", " ")[:19]
        return datetime.fromtimestamp(self.modified).strftime("%Y-%m-%d %H:%M:%S")


def sidecar_path(audio_path: Path) -> Path:
    return audio_path.with_suffix(".json")


def write_metadata(wav_path: Path, metadata: dict) -> Path:
    """Write ``<stem>.json`` atomically, refusing to replace an existing sidecar."""
    target = sidecar_path(Path(wav_path))
    payload = dict(metadata, owner=APP_OWNER)
    fd, temp_name = tempfile.mkstemp(prefix=".meta-", suffix=".tmp", dir=target.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False, indent=2)
        os.link(temp_name, target)  # fails with FileExistsError instead of overwriting
    finally:
        Path(temp_name).unlink(missing_ok=True)
    return target


def read_metadata(path: Path) -> tuple[dict | None, bool]:
    """Return (metadata, malformed). A missing sidecar is not malformed."""
    if not path.is_file():
        return None, False
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None, True
    return (data, False) if isinstance(data, dict) else (None, True)


def _duration(path: Path) -> float | None:
    try:
        return float(sf.info(str(path)).duration)
    except (RuntimeError, OSError):
        return None


def discover_history(output_dir: Path, query: str = "") -> list[HistoryItem]:
    output_dir = Path(output_dir)
    if not output_dir.is_dir():
        return []
    groups: dict[str, dict[str, Path]] = {}
    for path in output_dir.iterdir():
        if path.is_file() and path.suffix.lower() in _AUDIO_SUFFIXES and not path.name.startswith("."):
            groups.setdefault(path.stem, {})[path.suffix.lower()] = path
    query = (query or "").strip().lower()
    items = []
    for stem, files in groups.items():
        wav, mp3 = files.get(".wav"), files.get(".mp3")
        metadata, malformed = read_metadata(output_dir / f"{stem}.json")
        primary = wav or mp3
        item = HistoryItem(
            stem=stem, wav_path=wav, mp3_path=mp3, metadata=metadata,
            malformed_metadata=malformed,
            modified=max(p.stat().st_mtime for p in files.values()),
            size_bytes=sum(p.stat().st_size for p in files.values()),
            duration_seconds=_duration(primary),
        )
        haystack = f"{stem} {item.text} {(metadata or {}).get('reference_name', '')}".lower()
        if not query or query in haystack:
            items.append(item)
    return sorted(items, key=lambda i: i.modified, reverse=True)


def delete_item(output_dir: Path, stem: str) -> list[str]:
    """Delete one app-owned generation (audio + sidecar). Refuses anything else."""
    output_dir = Path(output_dir).resolve()
    if not _STEM.match(stem or ""):
        raise ValueError("Invalid item name.")
    meta_path = output_dir / f"{stem}.json"
    metadata, _malformed = read_metadata(meta_path)
    if not metadata or metadata.get("owner") != APP_OWNER:
        raise PermissionError("Only files generated by Telugu Voice Lab can be deleted here.")
    removed = []
    for path in (output_dir / f"{stem}.wav", output_dir / f"{stem}.mp3", meta_path):
        resolved = path.resolve()
        if resolved.parent != output_dir or path.is_symlink():
            raise PermissionError("Refusing to delete a path outside the output folder.")
        if path.is_file():
            path.unlink()
            removed.append(path.name)
    return removed
